USE aquanest_db;

DROP TABLE IF EXISTS conservation_tips;
CREATE TABLE conservation_tips (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(160) NOT NULL,
  category VARCHAR(60) NOT NULL,
  icon VARCHAR(30) NOT NULL DEFAULT 'daun',
  difficulty ENUM('Mudah','Sedang','Menantang') NOT NULL DEFAULT 'Mudah',
  summary VARCHAR(255) NOT NULL,
  description TEXT NOT NULL,
  related_species_id INT NULL,
  related_habitat_id INT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_tip_species FOREIGN KEY (related_species_id) REFERENCES species(id) ON DELETE SET NULL,
  CONSTRAINT fk_tip_habitat FOREIGN KEY (related_habitat_id) REFERENCES habitats(id) ON DELETE SET NULL
) ENGINE=InnoDB;

